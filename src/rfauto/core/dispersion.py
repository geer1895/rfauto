"""色散材料库：Debye / Djordjevic-Sarkar 因果宽带介电模型。

背景
----
模板库现有基板全部是常数 εr，宽带（>10 GHz 或超宽带）没有因果性保障。
本模块提供两类**确定性**（纯 numpy，无网络、无求解器）色散介电模型，
数据源 = 厂商 datasheet 单频点 (εr, tanδ) → 因果拟合：

* **Debye（单极 / 多极）**：ε(ω) = ε∞ + Σ_i Δε_i / (1 + j ω τ_i)
* **Djordjevic-Sarkar（D-S）**：以 1/f 加权、在 [f1, f2] 上连续叠加 Debye
  弛豫的因果宽带模型 [1]：

      ε(ω) = ε∞ + Δε / ln(f2/f1) · ln[(f2 + j f) / (f1 + j f)]

D-S 的**结构性因果保证**：它等价于无穷多 Debye 极点（每个极点单独满足
Kramers-Kronig 关系）的非负加权叠加，故整体必然满足 K-K。模块另提供
kramers_kronig_residual() 数值自检与 equivalent_debye() 有限多极对照。

口径与来源（与 openEMS 官方实现逐行对齐）
-----------------------------------------
openEMS 原生支持该模型，接口为
AddDjordjevicSarkarMaterial(CSX, name, 'fMeas', ..., 'epsRMeas', ...,
'tandMeas', ..., 'f1', ..., 'f2', ...)，内部调用
CalcDjordjevicSarkarApprox 由**单频点测量 + 频带端点**拟合：

* 官方文档（确证原生支持）：
  https://openems.readthedocs.io/en/latest/octave/autogenerated/CSXCAD/AddDjordjevicSarkarMaterial.html
* 参考实现（本工作区 vendor）：
  vendor/openEMS/install/share/CSXCAD/matlab/CalcDjordjevicSarkarApprox.m
  单点拟合（lowFreqEvalType=0）：

      k  = ln(10)·(-tanδ·εr - σ_DC/(ε0·ω_m)) / arg[(ω2 + jω_m)/(ω1 + jω_m)]
      ε∞ = εr - k·log10|(ω2 + jω_m)/(ω1 + jω_m)|
      Δε = k·(m2 - m1),   m = log10(ω),  ω = 2πf

* 符号约定：ε = ε' - jε''，tanδ = -Im(ε)/Re(ε) ≥ 0（与 openEMS 一致）。

文献
----
[1] A. R. Djordjevic, R. M. Biljie, V. D. Likar-Smiljanic, T. K. Sarkar,
    "Wideband frequency-domain characterization of FR-4 and time-domain
    causality," IEEE Trans. Electromagn. Compat., vol. 43, no. 4,
    pp. 662-667, 2001.
"""

