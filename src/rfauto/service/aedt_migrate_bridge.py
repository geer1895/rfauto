def plan_bridge_artifact_path(
    project_path: str | Path, work_root: str | Path, sha256_hex: str
) -> Path:
    """桥接产物路径**纯规划**：``<work_root>/bridged/<stem>__<sha8>.aedt``。

    sha8 锚定内容身份（S0 报告命名同款）；恒 ≠ 原件（bridged/ 新目录+
    sha8 后缀双保险，normcase 断言在执行器内）。桥接产物回迁 2025 R1
    重入 S1/S2 链时，这就是 direct_open 的输入路径。
    """
    project_path = Path(project_path)
    return Path(work_root) / "bridged" / f"{project_path.stem}__{sha256_hex[:8]}.aedt"


def build_bridge_saveas_script(
    staged_project: str | Path, target_project: str | Path
) -> str:
    """渲染桥接 save-as 脚本（纯函数；路径必须 ASCII，非 ASCII 即
    ``ValueError`` fail-closed——IronPython 脚本 ASCII 烘焙是中文路径坑
    的第一道门，staging 已保证 staged 侧 ASCII，target 侧由调用方保证
    （work_root 检查同款），本函数双查不豁免）。"""
    staged = str(staged_project)
    target = str(target_project)
    bad = [p for p in (staged, target) if has_non_ascii(p)]
    if bad:
        raise ValueError(
            f"桥接脚本路径含非 ASCII 字符: {bad}——IronPython 脚本路径必须"
            "纯 ASCII 烘焙（晶圆键合 §2.2）；请把 work_root/staging 指向"
            "纯 ASCII 目录。")
    return BRIDGE_SAVEAS_SCRIPT_TEMPLATE.format(
        staged_project=staged, target_project=target)


def build_bridge_command(
    ansysedt_exe: str | Path,
    script_path: str | Path,
    logfile: str | Path | None = None,
) -> list[str]:
    """拼 2023 R2 桥接命令行（纯函数，测试钉字面）。

    模板：``ansysedt.exe -ng [-Logfile <log>] -RunScript <script>``——
    参数序纪律（#374 家法，hfss_batch.build_batch_command 同源形态）：
    旗标在前、最后一个旗标（-RunScript）的操作数恒末位。``-ng``=非图形
    （蓝图 Stage 4 主通路形态）。2023 R2 真机旗标序实证挂账（本席不真
    跑；形态与 2025 R1 -ng -batchextract/-BatchSolve 已实证序一致）。
    """
    cmd = [str(ansysedt_exe), "-ng"]
    if logfile is not None:
        cmd += ["-Logfile", str(logfile)]
    cmd += ["-RunScript", str(script_path)]
    return cmd


def resolve_bridge_leg(bridge_config: Any) -> str:
    """桥接腿解析（纯函数）：``"none" | "local" | "remote"``。

    - ``None`` → ``"none"``（桥接机未配置 → S1 树/本执行器 BLOCKED）；
    - mapping 含 ``ansysedt_exe``（非空 str/Path）→ ``"local"``；
    - mapping 含 ``machine``（非空 str）→ ``"remote"``（挂账腿——发射
      配方见 remote_service.aedt_migrate，自动执行未接线）；
    - 两键并存=歧义 → ``ValueError``（配置错误要响，#122）；
    - 两键皆无 → ``ValueError``。
    """
    if bridge_config is None:
        return "none"
    if not isinstance(bridge_config, Mapping):
        raise ValueError(
            "bridge_2023R2 配置必须是 null 或 mapping，得到 "
            f"{type(bridge_config).__name__}")
    exe = bridge_config.get(_LOCAL_LEG_KEY)
    machine = bridge_config.get(_REMOTE_LEG_KEY)
    if exe and machine:
        raise ValueError(
            "bridge_2023R2 同时配置 ansysedt_exe 与 machine（歧义）——"
            "本地腿与远程腿二选一")
    if exe:
        return "local"
    if machine:
        return "remote"
    raise ValueError(
        "bridge_2023R2 mapping 缺 ansysedt_exe（本地腿）且缺 machine"
        "（远程腿）——至少配置其一，或置 null（=BLOCKED 语义缺省关）")


def build_bridge_executors(
    config: Mapping[str, Any] | None,
    *,
    runner: Callable[..., dict[str, Any]] | None = None,
) -> dict[str, Callable[[Path, dict[str, Any]], dict[str, Any]]]:
    """决策树 executors 注入工厂（只产出 ``bridge`` 键，其余阶段归 S2 席）。

    - bridge_2023R2 为 null / 缺键 → ``{}``（树按缺 executor → BLOCKED，
      S1 既有语义）；
    - 本地腿 → ``{"bridge": executor}``（executor 内部再读 context 配置，
      本工厂只做腿解析前置门）；
    - 远程腿 → ``{}``（**不注入**：远程桥接自动执行挂账，真机窗口未开；
      树按 BLOCKED 如实，不误报 FAILED_BRIDGE）。

    config 接受完整 ``aedt_migrate`` 配置块（dict|None）；bridge 子块
    形状非法 → ``ValueError`` 响亮（调用方配置错误前置暴露，不进树才炸）。
    """
    bridge_cfg = None
    if config is not None:
        bridge_cfg = config.get("bridge_2023R2")
    leg = resolve_bridge_leg(bridge_cfg)
    if leg != "local":
        return {}
    bound_runner = runner

    def _bridge_executor(
        project_path: Path, context: dict[str, Any]
    ) -> dict[str, Any]:
        return run_bridge_executor(
            project_path, context, runner=bound_runner)

    return {"bridge": _bridge_executor}


# ---------------------------------------------------------------------------
# runner（注入点；缺省=subprocess 真跑形态，本席不真跑）
# ---------------------------------------------------------------------------

def subprocess_runner(
    command: list[str],
    *,
    timeout_s: float | None = None,
) -> dict[str, Any]:
    """缺省 runner：subprocess 直调 ansysedt（2023 R2 安装后的真机形态）。

    返回 ``{"rc", "stdout_tail", "stderr_tail"}``（尾段截断
    :data:`_RUNNER_TAIL_CHARS`）。超时（TimeoutExpired）与任何 subprocess
    异常**原样传播**——基础设施故障不折算桥接 verdict（S1 契约：executor
    异常=批量层逐工程记 error 行）。
    """
    proc = subprocess.run(
        [str(c) for c in command],
        capture_output=True,
        timeout=timeout_s,
        check=False,
    )
    return {
        "rc": int(proc.returncode),
        "stdout_tail": proc.stdout.decode("utf-8", errors="replace")[
            -_RUNNER_TAIL_CHARS:],
        "stderr_tail": proc.stderr.decode("utf-8", errors="replace")[
            -_RUNNER_TAIL_CHARS:],
    }


# ---------------------------------------------------------------------------
# 执行器主体（S1 executor 契约：`(project_path, context) -> dict`）
# ---------------------------------------------------------------------------

def run_bridge_executor(
    project_path: str | Path,
    context: Mapping[str, Any],
    *,
    runner: Callable[..., dict[str, Any]] | None = None,
) -> dict[str, Any]:
    """Stage 4 桥接执行器（本地腿真形态；null/远程腿 → blocked 形态）。

    Args:
        project_path: 当前目标 .aedt（S1 树 cutoff 后调用时=原件路径；
            原件只读铁律：本执行器只读+staging 拷贝，写面全在 work_root）。
        context: S1 注入 context（``project_path/work_root/config/
            inventory_entry``；inventory_entry 缺 sha256 时就地补算）。
        runner: 注入执行通道（缺省 :func:`subprocess_runner`；测试一律
            注入 fake——本席不真跑，2023 R2 未装）。

    Returns:
        dict（S1 bridge executor 契约键 + 诊断扩展键）：

        - blocked 形态：``{"outcome": "blocked", "verdict":
          VERDICT_BLOCKED_NO_BRIDGE_HOST, "bridge_artifact": None,
          "messages": [...]}``——null 配置（S1 树在本执行器被调**之前**
          已自行 BLOCKED，此形态是独立消费/防御性双检）与远程腿（发射
          挂账）共用；
        - error 形态：``{"outcome": "error", ...}``——runner 非零退出 /
          产物未落盘（S1 树映射 FAILED_BRIDGE 如实）；
        - success 形态：``{"outcome": "success", "bridge_artifact":
          <path>, "engine_identity": {"ansysedt_version", "machine"},
          ...}``——树拿 artifact 重入 S1b/S2b/S3b。

    Raises:
        ValueError: 配置形状非法 / 路径含非 ASCII（契约类错误响亮上抛，
            不折算 verdict——S1 批量层逐工程记 error 行）。
        Exception: runner 内部异常原样传播（基础设施故障）。
    """
    project_path = Path(project_path)  # #140 PathLike 收敛
    cfg_block = context.get("config")
    bridge_cfg = cfg_block.get("bridge_2023R2") if isinstance(
        cfg_block, Mapping) else None
    leg = resolve_bridge_leg(bridge_cfg)

    if leg == "none":
        return {
            "outcome": "blocked",
            "verdict": VERDICT_BLOCKED_NO_BRIDGE_HOST,
            "bridge_artifact": None,
            "messages": [
                "bridge_2023R2=null（桥接机未配置）——Stage 4 前提不满足，"
                "如实 BLOCKED 非 FAIL（S1 枚举单源；设计稿 Stage 4）",
            ],
        }
    if leg == "remote":
        from rfauto.service.remote_service.aedt_migrate import (
            aedt_migrate_remote_recipe,
        )

        entry = context.get("inventory_entry") or {}
        stem = entry.get("project") or project_path.stem
        sha8 = str(entry.get("sha8") or sha256_file(project_path)[:8])
        recipe = aedt_migrate_remote_recipe(
            str(stem), sha8,
            machine=str(bridge_cfg.get("machine")),
        )
        return {
            "outcome": "blocked",
            "verdict": VERDICT_BLOCKED_NO_BRIDGE_HOST,
            "bridge_artifact": None,
            "messages": [
                "bridge_2023R2 指向远程腿（machine="
                f"{bridge_cfg.get('machine')}）——远程桥接自动执行挂账"
                "（2023 R2 未装/真机窗口未开），如实 BLOCKED 非 FAIL；"
                "远程发射清单见 result['remote_recipe']",
            ],
            "remote_recipe": recipe,
        }

    # ---- 本地腿 ----
    assert bridge_cfg is not None  # leg == "local"（resolve 已验形状）
    exe = bridge_cfg.get(_LOCAL_LEG_KEY)
    version = str(bridge_cfg.get("ansysedt_version") or BRIDGE_VERSION_DEFAULT)
    timeout_s = bridge_cfg.get("timeout_s")
    timeout_s = float(timeout_s) if timeout_s is not None else (
        BRIDGE_DEFAULT_TIMEOUT_S)
    if not exe or not str(exe).strip():
        raise ValueError(
            f"bridge_2023R2.ansysedt_exe 缺失或为空: {exe!r}——本地腿必需")

    work_root = Path(context.get("work_root") or Path.cwd()).resolve()
    entry = context.get("inventory_entry") or {}
    digest = str(entry.get("sha256") or sha256_file(project_path))
    sha8 = digest[:8]
    stem = str(entry.get("project") or project_path.stem)

    artifact = plan_bridge_artifact_path(project_path, work_root, digest)
    for guard_against in (project_path,):
        if _normcase(artifact) == _normcase(guard_against):
            raise ValueError(
                f"桥接产物路径与原件重合，拒绝（原件只读铁律）: {artifact}")

    messages: list[str] = [
        f"bridge version={version} exe={exe}",
        f"artifact plan={artifact}",
    ]
    failure_base: dict[str, Any] = {
        "outcome": "error",
        "bridge_artifact": None,
        "engine_identity": _engine_identity(version),
    }

    if has_non_ascii(work_root):
        raise ValueError(
            f"work_root 含非 ASCII 字符: {work_root}——桥接腿 staging/"
            "产物路径必须纯 ASCII（晶圆键合 §2.2 家族，fail-closed）")
    if not project_path.is_file():
        raise FileNotFoundError(f"待桥接工程不存在: {project_path}")

    # ASCII staging 拷贝（hfss_migrate 单源；非 ASCII 根其内部 fail-closed）
    stage_root = work_root / "bridge_stage" / f"{stem}_{sha8}"
    staged_info = stage_ascii_copy(project_path, stage_root=stage_root)
    staged_path = Path(staged_info["staged_path"])
    stage_dir = Path(staged_info["stage_dir"])
    if _normcase(artifact) == _normcase(staged_path):
        raise ValueError(
            f"桥接产物路径与 staging 拷贝件重合，拒绝: {artifact}")

    artifact.parent.mkdir(parents=True, exist_ok=True)
    script_path = stage_dir / BRIDGE_SCRIPT_NAME
    script_text = build_bridge_saveas_script(staged_path, artifact)
    script_path.write_text(script_text, encoding="ascii")
    log_path = stage_dir / "bridge_2023r2.log"
    command = build_bridge_command(exe, script_path, log_path)
    messages.append("command=" + subprocess.list2cmdline(command))

    run = (runner or subprocess_runner)(command, timeout_s=timeout_s)
    rc = int(run.get("rc", -1))
    messages.append(
        f"runner rc={rc}"
        + (f" stderr_tail={str(run.get('stderr_tail', ''))[-400:]}"
           if rc != 0 else ""))
    if rc != 0:
        return {
            **failure_base,
            "messages": messages,
            "runner_rc": rc,
            "log_path": str(log_path),
        }
    # post-verify（S2 save_as 同款"以文件在盘为准"）：SaveAs 无异常≠落盘。
    if not artifact.is_file():
        messages.append(
            "runner rc=0 但桥接产物未落盘——fail-closed 按 error"
            "（以文件在盘为准）")
        return {
            **failure_base,
            "messages": messages,
            "runner_rc": rc,
            "log_path": str(log_path),
        }
    stage_cleaned = _cleanup_stage(stage_dir, messages)
    return {
        "outcome": "success",
        "bridge_artifact": str(artifact),
        "messages": messages,
        "engine_identity": _engine_identity(version),
        "staged_path": str(staged_path),
        "stage_dir": str(stage_dir),
        "stage_cleaned": stage_cleaned,
        "runner_rc": rc,
        "log_path": str(log_path),
    }


def _normcase(path: str | Path) -> str:
    return os.path.normcase(str(path))


def _engine_identity(version: str) -> dict[str, Any]:
    """桥接机 engine_identity 原料（AX-3：S1 _build_engine_identity 单源
    消费；machine=桥接执行机 best-effort hostname）。"""
    try:
        machine = socket.gethostname() or "unknown"
    except Exception:  # pragma: no cover - 观测面兜底（#105）
        machine = "unknown"
    return {"ansysedt_version": version, "machine": machine}


def _cleanup_stage(stage_dir: Path, messages: list[str]) -> bool:
    """staging 清理（best-effort，任务毕清理纪律；stage 目录只有原件拷贝
    与脚本/日志——产物在 bridged/，删 stage 不伤产物）。"""
    import shutil

    try:
        shutil.rmtree(stage_dir, ignore_errors=True)
        messages.append(f"stage cleaned={stage_dir}")
        return True
    except Exception as exc:  # pragma: no cover - 平台兜底
        messages.append(f"staging 清理失败（留人工兜底）: {exc}")
        return False
