BRIDGE_SAVEAS_SCRIPT_TEMPLATE = """\
# aedt_migrate bridge save-as script (generated by rfauto; ASCII only)
# Purpose: open staged legacy project in bridge AEDT (2023 R2), SaveAs to
# target path WITHOUT overwrite (idempotent rerun refuses existing file).
# IronPython 2: no f-strings, no env reads, ASCII literals only.
import sys

STAGED_PROJECT = r"{staged_project}"
TARGET_PROJECT = r"{target_project}"


def _quit(oDesktop):
    # #374(4)/#265 house rule: batch script exit must QuitApplication,
    # otherwise orphan desktop process stays behind.
    try:
        oDesktop.QuitApplication()
    except Exception:
        pass


def main():
    oAnsys = sys.modules.get("__main__")
    oDesktop = oAnsys.GetAppDesktop() if hasattr(oAnsys, "GetAppDesktop") \
        else oAnsys.GetAppletDesktop("")
    try:
        oProject = oDesktop.OpenProject(STAGED_PROJECT)
        if oProject is None:
            raise RuntimeError(
                "OpenProject returned None: " + STAGED_PROJECT)
        oProject.SaveAs(TARGET_PROJECT, False)
    except Exception:
        _quit(oDesktop)
        raise
    _quit(oDesktop)


main()
"""


