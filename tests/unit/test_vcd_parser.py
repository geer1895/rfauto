# ── timescale 表驱动（档位闭集+换算已知量+fail-closed）──────────────────


class TestTimescale:
    @pytest.mark.parametrize(("raw", "expected"), [
        ("1fs", 1e-15),
        ("1ps", 1e-12),
        ("1ns", 1e-9),
        ("1us", 1e-6),
        ("1ms", 1e-3),
        ("1s", 1.0),
        ("10ps", 1e-11),
        ("100ns", 1e-7),
        ("10fs", 1e-14),
        ("100fs", 1e-13),
    ])
    def test_valid_table(self, raw: str, expected: float) -> None:
        # 换算=数值×单位基准（float 乘法舍入用紧 rel 钉——#118 家法小量判据）
        assert parse_timescale(raw) == pytest.approx(expected, rel=1e-15)

    def test_space_form(self) -> None:
        assert parse_timescale("10 ns") == 1e-8

    def test_case_insensitive(self) -> None:
        assert parse_timescale("1PS") == 1e-12

    def test_multiline_block_form(self) -> None:
        d = _mini("$enddefinitions $end\n", head="$timescale\n 10 ns\n$end\n")
        assert d["header"]["timescale_raw"] == "10 ns"
        assert d["header"]["timescale_factor_s"] == 1e-8

    def test_units_table_is_closed_set(self) -> None:
        # 档位闭集口径：表恰好六单位（fs..s），无伸缩口子
        assert set(TIMESCALE_UNIT_FACTORS) == {"FS", "PS", "NS", "US", "MS", "S"}

    @pytest.mark.parametrize("raw", [
        "5ps",      # 数值档位外
        "1000fs",   # 数值档位外
        "1xs",      # 未知单位
        "ps",       # 缺数值
        "1",        # 缺单位
        "1.5ns",    # 非整数档位
        "-1ps",     # 负值
        "",         # 空串
    ])
    def test_invalid_fail_closed(self, raw: str) -> None:
        with pytest.raises(VcdParseError):
            parse_timescale(raw)

    def test_error_is_value_error(self) -> None:
        # 任务书 fail-closed 口径：VcdParseError 必须是 ValueError 子类
        assert issubclass(VcdParseError, ValueError)


