class TestScopes:
    def test_top_level_name(self, doc: dict[str, Any]) -> None:
        assert list(doc["scopes"]) == ["top"]

    def test_children(self, doc: dict[str, Any]) -> None:
        assert set(doc["scopes"]["top"]["children"]) == {"alu", "rst_block"}

    def test_scope_type(self, doc: dict[str, Any]) -> None:
        assert doc["scopes"]["top"]["type"] == "module"

    def test_top_var_ids(self, doc: dict[str, Any]) -> None:
        assert doc["scopes"]["top"]["var_ids"] == ["!", '"', "%"]

    def test_alu_var_ids(self, doc: dict[str, Any]) -> None:
        assert doc["scopes"]["top"]["children"]["alu"]["var_ids"] == ["#", "$"]

    def test_rst_block_var_ids(self, doc: dict[str, Any]) -> None:
        rst = doc["scopes"]["top"]["children"]["rst_block"]
        assert rst["var_ids"] == ["&", "%"]

    @pytest.mark.parametrize(("vid", "path"), [
        ("!", "top"),
        ('"', "top"),
        ("#", "top.alu"),
        ("$", "top.alu"),
        ("&", "top.rst_block"),
    ])
    def test_scope_paths(self, doc: dict[str, Any], vid: str, path: str) -> None:
        assert doc["vars"][vid]["scope_path"] == path

    def test_three_level_nesting_and_begin_type(self) -> None:
        body = (
            "$scope module a $end\n"
            "$scope module b $end\n"
            "$scope begin c $end\n"
            "$var wire 1 ! s $end\n"
            "$upscope $end\n"
            "$upscope $end\n"
            "$upscope $end\n"
            "$enddefinitions $end\n"
        )
        d = _mini(body)
        assert d["vars"]["!"]["scope_path"] == "a.b.c"
        assert d["scopes"]["a"]["children"]["b"]["children"]["c"]["type"] == "begin"
        assert d["stats"]["n_scopes"] == 3

    def test_var_outside_scope(self) -> None:
        d = _mini("$var wire 1 ! lone $end\n$enddefinitions $end\n#5\n1!\n")
        assert d["scopes"] == {}
        assert d["vars"]["!"]["scope_path"] == ""
        assert d["events"]["!"] == [[5, "1"]]

    def test_duplicate_top_scope_override(self) -> None:
        body = (
            "$scope module t $end\n$upscope $end\n"
            "$scope module t $end\n$upscope $end\n"
            "$enddefinitions $end\n"
        )
        d = _mini(body)
        assert list(d["scopes"]) == ["t"]
        assert any("顶层 scope 重复名" in w for w in d["warnings"])


